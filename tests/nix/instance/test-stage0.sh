# An instance without a settings buffer has no buffer-derived paths.
copy=$(instance_copy "$nix_instance_fixtures/example")
rm -r "$copy/local-maintained-files"
assert_inst_eq '["~/.config/nix/nix.conf","~/.agents/skills","~/.config/example-app/state"]' \
  "(instance { root = /. + \"$copy\"; }).dotstewardManifest.x86_64-linux.backup_paths" "manifest backup paths"
nobuffer=$(stage0_dump "instance { root = /. + \"$copy\"; }" linux)
expect_array "$nobuffer" 'DS_STAGE0_BACKUP_PATHS=([0]="~/.config/nix/nix.conf" [1]="~/.agents/skills" [2]="~/.config/example-app/state")'

# [settings] buffer_dir moves the buffer.
copy=$(instance_copy "$nix_instance_fixtures/example")
mv "$copy/local-maintained-files" "$copy/settings-buffer"
printf '\n[settings]\nbuffer_dir = "settings-buffer"\n' >>"$copy/workstation.toml"
moved=$(stage0_dump "instance { root = /. + \"$copy\"; }" linux)
assert_contains "$moved" '[5]="~/.local/bin/example-script.sh"' "buffer_dir"

# An entry naming an unknown target is an error.
copy=$(instance_copy "$nix_instance_fixtures/example")
printf '\n[[entries]]\nid = "X1"\ntarget = "example-nope"\nkey = ["a"]\nvalue = 1\n' \
  >>"$copy/local-maintained-files/buffer.toml"
assert_inst_fails "(instance { root = /. + \"$copy\"; }).dotstewardMirrors.\"stage0.linux.env\"" \
  "dotsteward: local-maintained-files/buffer.toml: entry X1 names unknown target example-nope"

# A lock without the Nix pin cannot render stage-0.
copy=$(instance_copy "$nix_instance_fixtures/example")
jq 'del(.nix.installer_sha256)' "$nix_instance_fixtures/example/versions.lock.json" >"$copy/versions.lock.json"
assert_inst_fails "(instance { root = /. + \"$copy\"; }).dotstewardMirrors.\"stage0.linux.env\"" \
  "dotsteward: versions.lock.json lacks nix.installer_sha256 (required by component core)"
