# stage0_dump INSTANCE_EXPR PLATFORM: sources the stage-0 file in a clean
# bash and prints every DS_STAGE0_* variable (declare -p).
stage0_dump() {
  local file=$DS_TEST_ROOT/stage0.$2.env
  inst_raw "($1).dotstewardMirrors.\"stage0.$2.env\"" >"$file"
  bash -n "$file" || ds_fail "stage0.$2.env is not valid bash"
  assert_not_contains "$(<"$file")" "declare" "no declare in stage0.$2.env"
  assert_not_contains "$(<"$file")" "$(inst_raw 'builtins.storeDir')" "no store path in stage0.$2.env"
  env -i HOME=/nonexistent-home XDG_STATE_HOME=/nonexistent-state PATH=/nonexistent-bin \
    "$BASH" --norc --noprofile -c 'set -eu; source "$1"; declare -p ${!DS_STAGE0_@}' stage0 "$file"
}

linux=$(stage0_dump example linux)
header=$(inst_raw 'example.dotstewardMirrors."stage0.linux.env"' | sed -n '1,3p')
assert_contains "$header" "# Generated by dotsteward" "header"
assert_contains "$header" "dotsteward sync" "header names the command"

expect_var() {
  assert_contains "$1" "declare -- $2" "$2"
}
expect_array() {
  assert_contains "$1" "declare -a $2" "$2"
}

